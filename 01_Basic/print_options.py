''' sep: string inserted between objects(default: one space)
    end: string printed after the last object(default: newline)

'''

print("2026", "09", "30", sep="-") # Seprate by hyphen
print("a", "b", "c", sep="")
print("Loading", end="")
print("...", end=" ") # End with space
print("done!")
print("Abdus", "Samad", sep=" | ", end=" <--\n")
